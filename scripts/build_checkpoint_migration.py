"""Freeze the pinned langgraph-checkpoint-postgres DDL into a Supabase migration.

Reads PostgresSaver's MIGRATIONS list from the installed package's source with `ast`, without
importing it (importing would load psycopg's driver, which this step does not need). Writes the
statements for the `inventory_checkpoints` schema, drops CONCURRENTLY (a migration runs inside a
transaction), and records every version in checkpoint_migrations, so the runtime saver finds the
schema current and never upgrades it silently.

Usage: python scripts/build_checkpoint_migration.py [output.sql]
Review the output, then apply it as a NEW migration; never overwrite an applied one.
"""
import ast
from importlib.metadata import version
from importlib.util import find_spec
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'supabase' / 'migrations' / '004_inventory_checkpoints.sql'
PACKAGE = 'langgraph-checkpoint-postgres'

base = Path(find_spec('langgraph.checkpoint.postgres').submodule_search_locations[0]) / 'base.py'
tree = ast.parse(base.read_text(encoding='utf-8'))
migrations = next(ast.literal_eval(node.value) for node in tree.body
                  if isinstance(node, ast.Assign) and any(getattr(t, 'id', None) == 'MIGRATIONS' for t in node.targets))

statements = [' '.join(m.replace('CONCURRENTLY ', '').split()) for m in migrations]
tables = ['checkpoint_migrations', 'checkpoints', 'checkpoint_blobs', 'checkpoint_writes']
lines = [
    f'-- Generated by scripts/build_checkpoint_migration.py from {PACKAGE}=={version(PACKAGE)}.',
    f'-- {len(statements)} upstream migrations (versions 0-{len(statements) - 1}), CONCURRENTLY removed.',
    '-- The notebook connects as the database owner with search_path=inventory_checkpoints.',
    '',
    'set search_path = inventory_checkpoints;  -- works with or without a surrounding transaction',
    '',
    *[f'-- v{i}\n{sql}' for i, sql in enumerate(statements)],
    '',
    'reset search_path;',
    '',
    'insert into inventory_checkpoints.checkpoint_migrations (v) values '
    + ', '.join(f'({i})' for i in range(len(statements))) + ';',
    '',
    *[f'alter table inventory_checkpoints.{t} enable row level security;' for t in tables],
    'revoke all on all tables in schema inventory_checkpoints from public, anon, authenticated;',
    '',
]
OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'Wrote {OUT.relative_to(ROOT)} ({len(statements)} migrations, {PACKAGE}=={version(PACKAGE)})')
